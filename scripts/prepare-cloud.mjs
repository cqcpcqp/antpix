import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { LEVEL_COUNT, makeLevel } from '../assets/scripts/levels.ts';
const require = createRequire(import.meta.url);
const base = process.env.COCOS_RESOURCES || '/Applications/Cocos/Creator/3.8.8/CocosCreator.app/Contents/Resources';
const ts = require(base + '/app.asar.unpacked/node_modules/typescript');
const source = readFileSync('assets/scripts/profile.ts', 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
writeFileSync('cloudfunctions/game/profile.js', '// Generated by scripts/prepare-cloud.mjs; edit assets/scripts/profile.ts.\n' + code);
const levels = Array.from({ length: LEVEL_COUNT }, (_, index) => {
    const level = makeLevel(index);
    return { moves: [...new Set(level.containerPlans.map(plan => plan.length))],
        // Conservative lower bound: nine slots, 2x speed, no walking time.
        minimumSeconds: Math.max(0, (level.pixels.length - 9) * .25 / 9 - 2) };
});
writeFileSync('cloudfunctions/game/catalog.json', JSON.stringify({ levelCount: LEVEL_COUNT, levels }, null, 2) + '\n');
console.log('Cloud rules prepared for ' + LEVEL_COUNT + ' levels.');
