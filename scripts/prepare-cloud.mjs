import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { LEVEL_COUNT, makeLevel } from '../assets/scripts/levels.ts';
const require = createRequire(import.meta.url);
const base =
  process.env.COCOS_RESOURCES ||
  '/Applications/Cocos/Creator/3.8.8/CocosCreator.app/Contents/Resources';
const ts = require(base + '/app.asar.unpacked/node_modules/typescript');
const source = readFileSync('assets/scripts/profile.ts', 'utf8');
const code = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText;
writeFileSync(
  'cloudfunctions/game/profile.js',
  '// Generated by scripts/prepare-cloud.mjs; edit assets/scripts/profile.ts.\n' + code,
);
const levels = Array.from({ length: LEVEL_COUNT }, (_, index) => {
  const level = makeLevel(index);
  const moves = [...new Set(level.containerPlans.map((plan) => plan.length))];
  return {
    moves,
    // Conservative lower bound: nine slots, 4x finishing speed throughout,
    // and no walking/entry time. Every new jar dispatches its first ant
    // immediately; only the remaining ants require a 0.5 / 4 second interval.
    // Use the largest plan so this shared bound accepts every allowed plan.
    minimumSeconds: Math.max(0, ((level.pixels.length - Math.max(...moves)) * (0.5 / 4)) / 9 - 2),
  };
});
writeFileSync(
  'cloudfunctions/game/catalog.json',
  JSON.stringify({ levelCount: LEVEL_COUNT, levels }, null, 2) + '\n',
);
console.log('Cloud rules prepared for ' + LEVEL_COUNT + ' levels.');
