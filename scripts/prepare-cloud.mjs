import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { LEVEL_COUNT, makeLevel } from '../assets/scripts/domain/levels/levels.ts';
import {
  BASE_GAME_SPEED,
  DISPATCH_INTERVAL,
  FINISHING_SPEED,
} from '../assets/scripts/domain/game/timing.ts';
const require = createRequire(import.meta.url);
const base =
  process.env.COCOS_RESOURCES ||
  '/Applications/Cocos/Creator/3.8.8/CocosCreator.app/Contents/Resources';
const ts = require(base + '/app.asar.unpacked/node_modules/typescript');
for (const moduleName of ['profile', 'pets']) {
  const path = `assets/scripts/domain/profile/${moduleName}.ts`;
  const code = ts.transpileModule(readFileSync(path, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  writeFileSync(
    `cloudfunctions/game/${moduleName}.js`,
    `// Generated by scripts/prepare-cloud.mjs; edit ${path}.\n` + code,
  );
}
const levels = Array.from({ length: LEVEL_COUNT }, (_, index) => {
  const level = makeLevel(index);
  const moves = [...new Set(level.containerPlans.map((plan) => plan.length))];
  return {
    moves,
    // Conservative lower bound: nine slots, base-scaled finishing speed throughout,
    // and no walking/entry time. Every new jar dispatches its first ant
    // immediately; only the remaining ants require a scaled dispatch interval.
    // Use the largest plan so this shared bound accepts every allowed plan.
    minimumSeconds: Math.max(
      0,
      ((level.pixels.filter((color) => color >= 0).length - Math.max(...moves)) *
        (DISPATCH_INTERVAL / (BASE_GAME_SPEED * FINISHING_SPEED))) /
        9 -
        2,
    ),
  };
});
writeFileSync(
  'cloudfunctions/game/catalog.json',
  JSON.stringify({ levelCount: LEVEL_COUNT, levels }, null, 2) + '\n',
);
console.log('Cloud rules prepared for ' + LEVEL_COUNT + ' levels.');
