"""Pack generated artwork without warping; panels/buttons use runtime nine-slicing."""
from pathlib import Path
from PIL import Image, ImageFilter
import json

ROOT = Path(__file__).resolve().parents[3]
SOURCE = Path(__file__).parent
sheet = Image.open(SOURCE / 'components-master.png').convert('RGBA')
panel = Image.open(SOURCE / 'panel-master.png').convert('RGBA')
# Discard isolated low-opacity generation speckles while retaining antialiased silhouettes.
def trim(im):
    alpha = im.getchannel('A')
    alpha = alpha.point(lambda a: 0 if a < 80 else min(255, round(a * 255 / 253)))
    im.putalpha(alpha)
    return im.crop(alpha.getbbox())
regions = {
 'panel': (panel, None, 510, (85,145,85,95)),
 'gold': (sheet,(0,0,1024,326),768,(0,0,0,0)),
 'silver': (sheet,(0,330,512,575),336,(0,0,0,0)),
 'bronze': (sheet,(512,330,1024,575),336,(0,0,0,0)),
 'wreath': (sheet,(0,580,512,1020),256,(0,0,0,0)),
 'anonymous': (sheet,(550,590,978,998),240,(0,0,0,0)),
 'medal1': (sheet,(18,1034,237,1288),96,(0,0,0,0)),
 'medal2': (sheet,(266,1034,487,1288),96,(0,0,0,0)),
 'medal3': (sheet,(512,1034,732,1288),96,(0,0,0,0)),
 'sprig': (sheet,(766,1090,1000,1220),144,(0,0,0,0)),
 'button': (sheet,(30,1308,990,1528),480,(100,0,100,0)),
}
atlas=Image.new('RGBA',(1024,2048)); manifest={};x=y=rowh=0
for key,(source,box,width,insets) in regions.items():
 im=trim(source.crop(box) if box else source.copy())
 im=im.resize((width,round(im.height*width/im.width)),Image.Resampling.LANCZOS)
 if x+im.width+4>1024:x=0;y+=rowh+4;rowh=0
 atlas.alpha_composite(im,(x,y));manifest[key]={'rect':[x,y,im.width,im.height],'insets':list(insets)}
 x+=im.width+4;rowh=max(rowh,im.height)
assert y+rowh<=2048
out=ROOT/'assets/resources/leaderboard';out.mkdir(exist_ok=True)
atlas.save(out/'laurel.png',optimize=True)
(ROOT/'assets/scripts/presentation/leaderboardArt.ts').write_text('/** Generated by art/leaderboard/laurel-v2/prepare.py; shared atlas pixel regions. */\nexport const LEADERBOARD_ART = '+json.dumps(manifest,indent=4)+' as const;\nexport type LeaderboardArt = keyof typeof LEADERBOARD_ART;\n')
print('Atlas used height:',y+rowh)
